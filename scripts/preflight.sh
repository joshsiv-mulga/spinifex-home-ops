#!/usr/bin/env bash
# Everything this repo needs from a Spinifex cluster before `tofu apply` will
# work, that `just configure` cannot check itself.
#
# Platform seeding — the tenant CA, the images staged on a node — is a
# Spinifex cluster-admin concern and happens once per cluster, outside this
# repo (see the README's "0. A Spinifex cluster" checklist). This script is
# the repo's own half: confirming the CA you copied over is in place, writing
# it into the manifests that need it, checking the credentials profile works,
# checking Flux will be able to clone the repository, and staging the Talos
# image if it isn't imported yet.
#
# Idempotent. Run it again any time something looks stale.
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TFVARS="${REPO}/tofu/terraform.tfvars"

say() { printf '\n\033[1m==> %s\033[0m\n' "$1"; }
ok()  { printf '    \033[32m✓\033[0m %s\n' "$1"; }
warn(){ printf '    \033[33m!\033[0m %s\n' "$1"; }
die() { printf '    \033[31m✗\033[0m %s\n' "$1" >&2; exit 1; }

[[ -f "$TFVARS" ]] || die "no ${TFVARS} — run 'just configure' first"
tfvar() { awk -F'"' -v k="$1" '$0 ~ "^[[:space:]]*"k"[[:space:]]*=" {print $2; exit}' "$TFVARS"; }

PROFILE="$(tfvar aws_profile)"
GATEWAY="$(tfvar gateway_endpoint)"
REGION="$(tfvar region)"

# cluster.toml fields the tfvars render doesn't carry (schematic id, the
# optional SSH image-import helper) are read from the validated config
# directly, the same way `just template config-json` does.
CONFIG_JSON="$(cd "$REPO" && uv run --quiet --locked --no-dev template/scripts/validate.py cluster.toml)"
jcfg() { jq -r "$1 // empty" <<<"$CONFIG_JSON"; }
SCHEMATIC="$(jcfg '.talos.schematic_id')"
TALOS_VERSION="$(awk -F\' '/^talos_version :=/ {print $2; exit}' "${REPO}/talos/mod.just" | sed 's/^v//')"
SSH_HOST="$(jcfg '.spinifex.ssh_host')"
SSH_USER="$(jcfg '.spinifex.ssh_user')"
SSH_KEY="$(jcfg '.spinifex.ssh_key')"

# ---------------------------------------------------------------- platform CA
# The CA the gateway's server certificate chains to. tofu reads it via
# custom_ca_bundle; without it every API call fails certificate verification.
# Copied here by hand from /etc/spinifex/ca.pem on a node — see the README.
say "Platform CA"
CA_PEM="${REPO}/spinifex-ca.pem"
[[ -s "$CA_PEM" ]] || die "no spinifex-ca.pem — copy /etc/spinifex/ca.pem from a node (see README step 0)"
ok "spinifex-ca.pem present"

# --------------------------------------------------------------- CA manifests
# Every in-cluster consumer that verifies the gateway or Predastore against
# this CA needs its own copy, because none of them can read a file from the
# repo root. Collapsing to one source isn't possible: a ConfigMap has to be
# mounted per namespace, and kopia's S3 config takes its CA inline as base64
# rather than as a mounted file.
say "CA manifests"
emit_ca_configmap() {
    local dest="$1" name="$2"
    local tmp="${dest}.tmp"
    {
        printf -- '---\n'
        printf -- '# Generated by scripts/preflight.sh from the cluster'"'"'s own CA.\n'
        printf -- '# Do not edit; re-run the script after rebuilding the platform.\n'
        printf -- 'apiVersion: v1\nkind: ConfigMap\nmetadata:\n  name: %s\ndata:\n  ca.pem: |\n' "$name"
        sed 's/^/    /' "$CA_PEM"
    } > "$tmp"
    if cmp -s "$tmp" "$dest" 2>/dev/null; then
        rm -f "$tmp"; ok "$(realpath --relative-to="$REPO" "$dest") already current"
    else
        mv "$tmp" "$dest"; ok "wrote $(realpath --relative-to="$REPO" "$dest")"
    fi
}
emit_ca_configmap "${REPO}/kubernetes/components/volsync/configmap.yaml" spinifex-ca
emit_ca_configmap "${REPO}/kubernetes/apps/kube-system/aws-ebs-csi-driver/app/ca-configmap.yaml" spinifex-ca
emit_ca_configmap "${REPO}/kubernetes/apps/storage/volsync/maintenance/configmap.yaml" spinifex-ca

# kopia's S3 storage config is one JSON blob embedded in the HelmRelease, and
# the CA has to be base64 inside it rather than mounted — there's nowhere
# else in that config to point it at a file.
KOPIA_HR="${REPO}/kubernetes/apps/storage/kopia/app/helmrelease.yaml"
KOPIA_CA_B64="$(base64 -w0 < "$CA_PEM")"
if grep -q "\"rootCA\": \"${KOPIA_CA_B64}\"" "$KOPIA_HR"; then
    ok "kopia/app/helmrelease.yaml rootCA already current"
else
    sed -i -E "s#\"rootCA\": \"[A-Za-z0-9+/=]*\"#\"rootCA\": \"${KOPIA_CA_B64}\"#" "$KOPIA_HR"
    ok "wrote kopia/app/helmrelease.yaml rootCA"
fi

# ------------------------------------------------------------- AWS profile
# `spx admin init` writes this profile on the node; only its credentials are
# used here. Its endpoint_url (localhost on the node) and ca_bundle (a path on
# the node) are wrong from a workstation, so every call passes the gateway and
# the copied CA itself.
awsx() {
    AWS_PROFILE="$PROFILE" AWS_CA_BUNDLE="${REPO}/spinifex-ca.pem" \
        aws --endpoint-url "$GATEWAY" --region "$REGION" "$@"
}

say "AWS profile"
aws configure get aws_access_key_id --profile "$PROFILE" >/dev/null 2>&1 \
    || die "no ${PROFILE} profile — copy ~/.aws/credentials from a node (see README step 0)"
if ERR="$(awsx ec2 describe-regions --output text 2>&1 >/dev/null)"; then
    ok "profile ${PROFILE} authenticates against ${GATEWAY}"
else
    die "profile ${PROFILE} cannot reach ${GATEWAY}: ${ERR}"
fi

# ----------------------------------------------------------- Git repository
# Flux clones [repository] url with no credentials of its own over https, and
# with deploy.key over ssh. Checked the same way here, so a private repo behind
# an https URL, or a deploy key not yet added to the repo, fails now rather
# than as a FluxInstance timing out at the end of `just bootstrap apps`.
say "Git repository"
REPO_URL="$(jcfg '.repository.url')"
REPO_BRANCH="$(jcfg '.repository.branch')"
# No credential helper, no prompt, no agent keys: only what Flux will have.
GIT_ENV=(env GIT_TERMINAL_PROMPT=0 GIT_ASKPASS=/usr/bin/false SSH_ASKPASS=/usr/bin/false)
if [[ "$REPO_URL" == ssh://* ]]; then
    [[ -f "${REPO}/deploy.key" ]] || die "no deploy.key — run 'just init' first"
    GIT_ENV+=("GIT_SSH_COMMAND=ssh -i '${REPO}/deploy.key' -o IdentitiesOnly=yes -o IdentityAgent=none -o BatchMode=yes -o StrictHostKeyChecking=accept-new")
fi
if ! HEADS="$("${GIT_ENV[@]}" git -c credential.helper= ls-remote --heads "$REPO_URL" "$REPO_BRANCH" 2>&1)"; then
    printf '%s\n' "$HEADS" | sed 's/^/      /' >&2
    if [[ "$REPO_URL" == ssh://* ]]; then
        die "Flux can't read ${REPO_URL} with deploy.key — add deploy.key.pub to the repo as a read-only deploy key"
    fi
    die "Flux can't read ${REPO_URL} without credentials — if the repo is private, use its ssh:// URL in cluster.toml and re-run 'just configure'"
fi
if [[ -z "$HEADS" ]]; then
    warn "branch '${REPO_BRANCH}' isn't on the remote yet — push it before 'just bootstrap apps' (README step 4)"
else
    ok "Flux can read ${REPO_URL} (branch ${REPO_BRANCH})"
fi

# --------------------------------------------------------------- Talos image
# Imported once per cluster rather than kept as a file. Staging it over SSH is
# optional: set spinifex.ssh_host (+ ssh_user, optionally ssh_key) in
# cluster.toml to let this script do it; otherwise it prints the commands to
# run by hand and moves on rather than failing.
say "Talos image"
[[ -n "$SCHEMATIC" ]] || die "no talos.schematic_id in cluster.toml"
FACTORY="https://factory.talos.dev/image/${SCHEMATIC}/v${TALOS_VERSION}/aws-amd64.raw.xz"

FOUND="$(awsx ec2 describe-images \
            --filters 'Name=name,Values=*talos*' \
            --query 'Images[].Name' --output text)"

if [[ -n "$FOUND" ]]; then
    ok "already imported: ${FOUND}"
elif [[ -n "$SSH_HOST" ]]; then
    [[ -n "$SSH_USER" ]] || die "spinifex.ssh_user is required alongside spinifex.ssh_host"
    # -t: the import needs sudo, which on a standard install asks for a
    # password and so needs a terminal to ask on.
    SSH=(ssh -t -o StrictHostKeyChecking=accept-new)
    [[ -n "$SSH_KEY" ]] && SSH+=(-i "$SSH_KEY")
    SSH+=("${SSH_USER}@${SSH_HOST}")
    STAGED="images/talos-${TALOS_VERSION}.raw"
    warn "not imported — fetching from the factory via ${SSH_HOST}"
    echo "      schematic ${SCHEMATIC:0:12}… version v${TALOS_VERSION}"
    echo "      the import runs under sudo on ${SSH_HOST}; it may ask for your password"
    # sudo -v first, so the password prompt comes before the download rather
    # than after it.
    "${SSH[@]}" "set -e; sudo -v; mkdir -p \$HOME/images \$HOME/images/tmp
        curl -fSL --retry 3 '${FACTORY}' | xz -dc > \$HOME/${STAGED}.part
        mv \$HOME/${STAGED}.part \$HOME/${STAGED}
        sudo spx admin images import --file \$HOME/${STAGED} --arch x86_64 \
            --distro talos --version ${TALOS_VERSION} --boot-mode uefi \
            --tmp-dir \$HOME/images/tmp
        rm -f \$HOME/${STAGED}"
    ok "imported ami-talos-${TALOS_VERSION}-x86_64"
else
    warn "not imported, and no spinifex.ssh_host set"
    echo "    Set spinifex.ssh_host and ssh_user in cluster.toml and re-run to have"
    echo "    this script do it, or import it yourself. On a node:"
    echo
    echo "      curl -fSL '${FACTORY}' | xz -dc > talos-${TALOS_VERSION}.raw"
    echo "      sudo spx admin images import \\"
    echo "          --file talos-${TALOS_VERSION}.raw --arch x86_64 --distro talos \\"
    echo "          --version ${TALOS_VERSION} --boot-mode uefi"
    echo
    echo "    If the node can't reach the internet, download it here and copy it"
    echo "    over still compressed, then decompress it on the node before importing:"
    echo
    echo "      curl -fSLO '${FACTORY}'"
    echo "      scp aws-amd64.raw.xz <a-node>:talos-${TALOS_VERSION}.raw.xz"
    echo "      ssh <a-node> xz -d talos-${TALOS_VERSION}.raw.xz"
    echo
    echo "    Re-run this script afterwards to confirm it's picked up."
fi

say "Done"
echo "    next: just bootstrap talos && (cd tofu && tofu init && tofu apply)"
