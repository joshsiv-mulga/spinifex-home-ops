#!/usr/bin/env bash
# Builds cluster-secrets from what `tofu apply` already knows.
#
# Every value here is either an output of the environment or a password nothing
# outside this cluster needs to know. Neither is worth a human copying by hand,
# and the endpoints in particular change on every rebuild.
#
# Generated passwords are read back from the existing file and kept. Rotating
# VOLSYNC_KOPIA_PASSWORD would leave the backup repository unreadable, which is
# a bad thing to do by accident on a re-run.
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DEST="${REPO}/kubernetes/components/sops/cluster-secrets.sops.yaml"
export SOPS_AGE_KEY_FILE="${SOPS_AGE_KEY_FILE:-${REPO}/age.key}"

say() { printf '\n\033[1m==> %s\033[0m\n' "$1"; }
ok()  { printf '    \033[32m✓\033[0m %s\n' "$1"; }
die() { printf '    \033[31m✗\033[0m %s\n' "$1" >&2; exit 1; }

command -v sops >/dev/null || die "sops not on PATH"
command -v tofu >/dev/null || die "tofu not on PATH"
[[ -f "$SOPS_AGE_KEY_FILE" ]] || die "no age key at ${SOPS_AGE_KEY_FILE} — run 'just configure' first"

say "Reading the environment"
cd "${REPO}/tofu"
tofu output -json > /tmp/.render-secrets-outputs.$$ 2>/dev/null || die "no tofu state — apply the environment first"
trap 'rm -f /tmp/.render-secrets-outputs.$$' EXIT

out() { python3 -c "import json,sys; d=json.load(open('/tmp/.render-secrets-outputs.$$')); print(d['$1']['value'])" 2>/dev/null; }
for k in db_endpoint db_master_username db_master_password nfs_address nfs_export \
         volsync_bucket volsync_key_id volsync_key_secret s3_endpoint; do
    [[ -n "$(out "$k")" ]] || die "output ${k} missing — apply the environment first"
done
ok "9 outputs read"

# ------------------------------------------------------------------- passwords
# Kept if they already exist, so a re-run never invalidates a backup repository
# or locks anyone out of a dashboard.
say "Passwords"
keep() {
    local key="$1" existing=""
    if [[ -f "$DEST" ]]; then
        existing="$(sops -d "$DEST" 2>/dev/null | awk -v k="$key" '$1==k":" {print $2}')"
    fi
    if [[ -n "$existing" ]]; then
        printf '%s' "$existing"; printf '    kept %s\n' "$key" >&2
    else
        openssl rand -base64 24 | tr -d '/+=' | head -c 32
        printf '    generated %s\n' "$key" >&2
    fi
}
KOPIA_PW="$(keep VOLSYNC_KOPIA_PASSWORD)"
ATUIN_PW="$(keep ATUIN_DB_PASSWORD)"
GRAFANA_PW="$(keep GRAFANA_ADMIN_PASSWORD)"

DOMAIN="$(awk -F'"' '/^[[:space:]]*domain[[:space:]]*=/ {print $2; exit}' "${REPO}/tofu/terraform.tfvars")"
[[ -n "$DOMAIN" ]] || die "no domain in terraform.tfvars"
REGION="$(awk -F'"' '/^[[:space:]]*region[[:space:]]*=/ {print $2; exit}' "${REPO}/tofu/terraform.tfvars")"
[[ -n "$REGION" ]] || die "no region in terraform.tfvars"

say "Writing ${DEST##*/}"
TMP="${DEST%.sops.yaml}.tmp.sops.yaml"
cat > "$TMP" <<EOF
---
# Generated by scripts/render-secrets.sh from tofu outputs.
# Re-run it after rebuilding the environment; passwords already here are kept.
apiVersion: v1
kind: Secret
metadata:
  name: cluster-secrets
  namespace: flux-system
stringData:
  SECRET_DOMAIN: ${DOMAIN}
  SPINIFEX_REGION: ${REGION}
  RDS_ENDPOINT: $(out db_endpoint)
  RDS_MASTER_USERNAME: $(out db_master_username)
  RDS_MASTER_PASSWORD: $(out db_master_password)
  ATUIN_DB_PASSWORD: ${ATUIN_PW}
  GRAFANA_ADMIN_PASSWORD: ${GRAFANA_PW}
  NFS_SERVER: $(out nfs_address)
  NFS_EXPORT: $(out nfs_export)
  VOLSYNC_S3_BUCKET: $(out volsync_bucket)
  VOLSYNC_S3_ENDPOINT: $(out s3_endpoint)
  VOLSYNC_KEY_ID: $(out volsync_key_id)
  VOLSYNC_KEY_SECRET: $(out volsync_key_secret)
  VOLSYNC_KOPIA_PASSWORD: ${KOPIA_PW}
EOF

# sops picks its store from the extension, so the temp file has to keep the
# .sops.yaml suffix or it is encrypted as an opaque binary blob Flux cannot read.
sops --encrypt --input-type yaml --output-type yaml --in-place "$TMP"
mv "$TMP" "$DEST"
ok "encrypted to $(basename "$SOPS_AGE_KEY_FILE")'s recipient"

say "Done"
printf '    commit it, then: flux reconcile ks flux-system --with-source\n\n'
